"""M17: Canonical Telemetry Simulator for Independent Development & End-to-End Verification.

Provides deterministic simulation of canonical telemetry events across all operational,
degraded, anomaly, failure, and recovery scenarios without requiring a live UAV hardware connection.

Scenarios Supported:
1. NORMAL: Stable flight, healthy battery, nominal vibration (RMS ~1.8 mm/s), normal temperatures.
2. VIBRATION_DEGRADATION: Controlled rising vibration (from nominal -> elevated 5.5 mm/s -> critical 8.8 mm/s)
   with elevated kurtosis and crest factor to exercise fault signatures (bearing degradation, rotor imbalance).
3. TEMPERATURE_ANOMALY: Rising motor/ESC temperatures breaching warning thresholds.
4. BATTERY_DEGRADATION: Depleting voltage, rising internal resistance, high cycle counts.
5. TELEMETRY_STALENESS: Historical timestamp generation simulating telemetry gap / connection loss.
6. TELEMETRY_RECOVERY: Resumption of real-time telemetry stream after staleness.
7. SENSOR_ANOMALY: Single divergent sensor on a multi-sensor component.
8. FAILURE_HANDLING: Duplicate events, out-of-order packets, invalid measurements, degraded quality flags.
"""

